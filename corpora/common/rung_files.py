"""Files a rung's `prepare.py` writes beside its data: vocabularies and the deployment file."""

from __future__ import annotations

import os
import secrets
from pathlib import Path

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq


def write_vocabulary(out: Path, name: str, keys: list[str]) -> int:
    """`vocab-<name>.parquet`, each key its own title. Code 0 is the absent sentinel and is
    refused in a declared set, so the codes start at one."""
    pq.write_table(
        pa.table(
            {
                "key": pa.array(keys, pa.string()),
                "code": pa.array(np.arange(1, len(keys) + 1, dtype=np.uint32), pa.uint32()),
                "title": pa.array(keys, pa.string()),
            }
        ),
        out / f"vocab-{name}.parquet",
    )
    return len(keys)


def write_deployment(out: Path, *, generator: str, credential_env: str) -> None:
    """`mosaica.toml`, generated rather than committed because every value in it is a path or a
    port on this machine, with an operator credential minted into `.env` where none is held.

    Every rung serves on 8141-8143, so one demo viewer reaches whichever rung is up.
    """
    (out / "mosaica.toml").write_text(
        f"""# Generated by `{generator}`. Machine-specific by construction: paths
# and ports, and the *names* of the variables carrying the credentials, never the values.

[bundle]
path  = "bundle"
cache = ".mosaica/cache"
wal   = ".mosaica/wal.log"

[build]
schema = "corpus.toml"

[disclosure]
token_max_lifetime = 3600

[catalogue]
dir = ".mosaica/catalogue"

[serve]
viewer  = "127.0.0.1:8141"
session = "127.0.0.1:8142"
control = "127.0.0.1:8143"
max_k   = 5000
operator_credential_env = "{credential_env}"

# Development only: the origin the demo viewer is served from. Without
# it the viewer loads and every request from it fails CORS, which reads like a broken server.
dev_cors_origins = ["http://localhost:PORT", "http://127.0.0.1:PORT"]
"""
        .replace("PORT", os.environ.get("VITE_PORT", "5178")),
        encoding="utf-8",
    )

    # The server does not create the directory its WAL and cache sit in.
    (out / ".mosaica").mkdir(exist_ok=True)

    # Minted once, so a rerun keeps the value a running client already holds.
    env = out / ".env"
    lines = env.read_text().splitlines() if env.exists() else []
    held = {line.split("=", 1)[0] for line in lines if "=" in line}
    if credential_env not in held:
        env.write_text("\n".join(lines + [f"{credential_env}={secrets.token_hex(16)}"]) + "\n")
        env.chmod(0o600)
        print(f"minted {credential_env} in {env}")
